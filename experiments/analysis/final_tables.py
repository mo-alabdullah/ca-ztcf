def _table(headers: list[str], rows: list[list[Any]]) -> str:
    head = "| " + " | ".join(headers) + " |"
    rule = "|" + "|".join(["---"] * len(headers)) + "|"
    body = "\n".join(
        "| " + " | ".join("" if c is None else str(c) for c in row) + " |" for row in rows
    )
    return f"{head}\n{rule}\n{body}\n"


def _page(title: str, intro: str, body: str) -> str:
    return (
        f"# {title}\n\n"
        f"> **{BANNER}**\n>\n"
        "> Generated by `scripts/process_final_results.py`. Descriptive statistics\n"
        "> only in this file; tests and effect sizes are in Table K.\n\n"
        f"{intro}\n\n{body}"
    )


def _fmt(value: Any, places: int = 3) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.{places}f}"
    return str(value)


def _rate_with_denominator(rate: Any, numerator: int, denominator: int) -> str:
    """A rate never appears without the counts it was computed from."""
    return f"{_fmt(rate, 4)} ({numerator}/{denominator})"


def _describe_row(label: str, values: list[float]) -> list[Any]:
    d = describe(values)
    return [
        label,
        d["n"],
        _fmt(d["median"]),
        _fmt(d["iqr"]),
        _fmt(d["p95"]),
        _fmt(d["min"]),
        _fmt(d["max"]),
    ]


# --- Table A ---------------------------------------------------------------


def table_a(runs: list[FinalRun], root: Path) -> str:
    path = root / "metadata" / "environment.json"
    if not path.is_file():
        raise FileNotFoundError(
            f"{path} is missing. Table A reports the environment the campaign ran "
            "in, and every value must come from the machine that reported it. Run "
            "scripts/collect_tier2_environment.py; nothing here is typed by hand."
        )
    environment = json.loads(path.read_text(encoding="utf-8"))
    rows = [
        ["Host", environment["host"]],
        ["Virtualisation", environment["virtualisation"]],
        ["Guest OS", environment["guest_os"]],
        ["Guest kernel", environment["kernel"]],
        ["Architecture", environment["arch"]],
        ["Guest resources", environment["resources"]],
        ["5G core", environment["open5gs"]],
        ["5G RAN and UE", environment["ueransim"]],
        ["WLAN", environment["wlan"]],
        ["Subscriber database", environment["mongodb"]],
        ["MQTT broker", environment["mosquitto"]],
        ["Runtime", environment["python"]],
        ["Access namespaces", environment["access_namespaces"]],
        ["Physical radio", f"**{environment['physical_radio']}**"],
        ["Recorded at", environment["collected_at"]],
    ]
    return _page(
        "Table A — testbed environment",
        "The environment every final run executed in, read from the running "
        "machine. There is no physical radio anywhere in it.",
        _table(["Component", "Value"], rows),
    )


# --- Table B ---------------------------------------------------------------


def table_b(runs: list[FinalRun], root: Path) -> str:
    scenarios = {s.scenario_id: s for s in load_scenarios(REPO / "experiments" / "scenarios")}
    rows = []
    for scenario_id in sorted(SCENARIO_TITLES):
        scenario = scenarios.get(scenario_id)
        executed = sorted({r.condition for r in runs if r.scenario == scenario_id})
        rows.append(
            [
                scenario_id,
                SCENARIO_TITLES[scenario_id],
                scenario.device_count if scenario else "-",
                "yes" if scenario_id in ADVERSARIAL_SCENARIOS else "no",
                ", ".join(executed) if executed != ["default"] else "single condition",
            ]
        )
    intro = (
        "The fifteen scenarios, used exactly as validated. E13 is the only scenario "
        "executed at several conditions: 1, 5, 10 and 25 logical devices. E14 sweeps "
        "the four validated transition rates (1, 5, 10, 25 per second) inside a "
        "single run."
    )
    return _page(
        "Table B — scenario definitions",
        intro,
        _table(["Id", "Subject", "Devices", "Adversarial", "Conditions"], rows),
    )


# --- Table C ---------------------------------------------------------------


def table_c(runs: list[FinalRun], root: Path) -> str:
    subjects: dict[str, set[str]] = defaultdict(set)
    for run in runs:
        for metric, subject in (run.metadata.get("metric_subjects") or {}).items():
            subjects[metric].add(str(subject))
    rows = []
    for metric_id, definition in METRIC_DEFINITIONS.items():
        observed = ", ".join(sorted(subjects.get(metric_id, set()))) or "-"
        rows.append([metric_id, definition.name, definition.unit, observed, definition.definition])
    intro = (
        "What each metric measures, and the subject each run recorded for it. The "
        "subject matters: a decision latency and an access-context latency are not "
        "comparable, and neither is a measurement of a radio.\n\n"
        "**Timing quantities are distinct and are never conflated:** access "
        "authentication latency, path-switch latency, trust decision latency, "
        "application recovery latency and end-to-end transition duration. In the "
        "transition records, `T4 → T5` includes agent process start-up and is **not** "
        "pure decision latency; the decision alone is `trust_decision_ms`."
    )
    return _page(
        "Table C — metric definitions",
        intro,
        _table(["Id", "Name", "Unit", "Subject observed", "Definition"], rows),
    )


