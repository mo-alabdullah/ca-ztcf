# --- Table E ---------------------------------------------------------------


def table_e(runs: list[FinalRun], root: Path) -> str:
    rows = []
    for scenario in ADVERSARIAL_SCENARIOS:
        for strategy in PRIMARY:
            totals: Counter = Counter()
            n = 0
            for run in runs:
                if (run.campaign, run.scenario, run.strategy) == ("primary", scenario, strategy):
                    totals.update({k: v for k, v in run.confusion.items() if isinstance(v, int)})
                    n += 1
            r = confusion_rates(dict(totals))
            rows.append(
                [
                    scenario,
                    LABELS[strategy],
                    n,
                    r["counts"]["TP"],
                    r["counts"]["TN"],
                    r["counts"]["FP"],
                    r["counts"]["FN"],
                    _rate_with_denominator(
                        r["false_acceptance_rate"],
                        r["counts"]["FN"],
                        r["false_acceptance_denominator"],
                    ),
                    _rate_with_denominator(
                        r["false_rejection_rate"],
                        r["counts"]["FP"],
                        r["false_rejection_denominator"],
                    ),
                    _fmt(r["detection_rate_recall"], 4),
                ]
            )
    intro = (
        "Raw confusion counts summed over 30 runs per cell, with every rate shown "
        "beside the counts it came from. TP and FN are over adversarial events; TN "
        "and FP are over legitimate ones. False acceptance is an adversarial event "
        "permitted; false rejection is a legitimate event denied or quarantined.\n\n"
        "These counts are **not** independent observations — they aggregate events "
        "within runs. The paired tests in Table K use one binary outcome per run, "
        "which is the experimental unit."
    )
    return _page(
        "Table E — primary security outcomes",
        intro,
        _table(
            [
                "Scenario",
                "Strategy",
                "Runs",
                "TP",
                "TN",
                "FP",
                "FN",
                "False acceptance (n/N)",
                "False rejection (n/N)",
                "Recall",
            ],
            rows,
        ),
    )


# --- Table F ---------------------------------------------------------------


def table_f(runs: list[FinalRun], root: Path) -> str:
    rows = []
    for scenario in TRANSITION_SCENARIOS:
        for strategy in PRIMARY:
            values = [
                r.metrics["transition_ms_median"]
                for r in runs
                if (r.campaign, r.scenario, r.strategy) == ("primary", scenario, strategy)
                and r.metrics["transition_ms_median"] is not None
            ]
            if values:
                rows.append([scenario, *_describe_row(LABELS[strategy], values)])
    intro = (
        "Transition duration per run: access-context switch initiated to the first "
        "decision under the new context. Software-testbed timing on a single host; "
        "**not** a physical handover measurement."
    )
    return _page(
        "Table F — transition latency",
        intro,
        _table(["Scenario", "Strategy", "n", "Median (ms)", "IQR", "p95", "Min", "Max"], rows),
    )


