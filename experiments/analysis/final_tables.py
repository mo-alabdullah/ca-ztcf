# --- Table H ---------------------------------------------------------------


def table_h(runs: list[FinalRun], root: Path) -> str:
    rows = []
    for scenario in sorted({r.scenario for r in runs if r.campaign == "primary"}):
        for strategy in PRIMARY:
            selected = [
                r
                for r in runs
                if (r.campaign, r.scenario, r.strategy) == ("primary", scenario, strategy)
                and r.condition in ("default", "devices=25")
            ]
            if not selected:
                continue
            reauth = [float(r.metrics["reauthentications"]) for r in selected]
            step = [float(r.metrics["step_ups"]) for r in selected]
            changes = [float(r.metrics["state_changes"]) for r in selected]
            rows.append(
                [
                    scenario,
                    LABELS[strategy],
                    len(selected),
                    int(sum(reauth)),
                    _fmt(describe(reauth)["median"], 1),
                    int(sum(step)),
                    _fmt(describe(step)["median"], 1),
                    int(sum(changes)),
                ]
            )
    intro = (
        "Authentication actions issued, as raw totals over 30 runs with the per-run "
        "median beside them. A re-authentication is a full REAUTHENTICATE action; a "
        "step-up is STEP_UP_AUTHENTICATION, which holds protected operations until "
        "answered."
    )
    return _page(
        "Table H — authentication actions",
        intro,
        _table(
            [
                "Scenario",
                "Strategy",
                "Runs",
                "Re-auth total",
                "Re-auth median",
                "Step-up total",
                "Step-up median",
                "State changes",
            ],
            rows,
        ),
    )


# --- Table I ---------------------------------------------------------------


def table_i(runs: list[FinalRun], root: Path) -> str:
    rows = []
    for strategy in PRIMARY:
        selected = [r for r in runs if r.campaign == "primary" and r.strategy == strategy]
        cpu = [r.metrics["cpu_seconds"] for r in selected if r.metrics["cpu_seconds"] is not None]
        mem = [
            r.metrics["memory_mib_peak"]
            for r in selected
            if r.metrics["memory_mib_peak"] is not None
        ]
        msg = [float(r.metrics["messages"]) for r in selected]
        byt = [float(r.metrics["bytes"]) for r in selected]
        rows.append(
            [
                LABELS[strategy],
                len(selected),
                _fmt(describe(cpu)["median"], 4),
                _fmt(describe(cpu)["p95"], 4),
                _fmt(describe(mem)["median"], 1),
                _fmt(describe(mem)["p95"], 1),
                _fmt(describe(msg)["median"], 1),
                _fmt(describe(byt)["median"], 1),
            ]
        )
    intro = (
        "Resource cost per run across the whole primary campaign.\n\n"
        "**Subject: the experiment process**, which runs the trust function together "
        "with the scenario driver. This is **not** an IoT device measurement — the "
        "device agent is a separate process and, on Tier 2, lives in another network "
        "namespace. CPU is CPU seconds over the run; interval-sampled utilisation is "
        "undefined for runs shorter than one sampling interval, and shortening the "
        "interval would perturb the latency being measured."
    )
    return _page(
        "Table I — resource usage",
        intro,
        _table(
            [
                "Strategy",
                "Runs",
                "CPU s median",
                "CPU s p95",
                "Peak RSS MiB median",
                "Peak RSS MiB p95",
                "Messages median",
                "Bytes median",
            ],
            rows,
        ),
    )


# --- Table J ---------------------------------------------------------------


def table_j(runs: list[FinalRun], root: Path) -> str:
    rows = []
    for level in E13_LEVELS:
        for strategy in PRIMARY:
            selected = [
                r
                for r in runs
                if r.campaign == "primary"
                and r.scenario == "E13"
                and r.strategy == strategy
                and r.device_count == level
            ]
            if not selected:
                continue
            lat = [
                r.metrics["decision_latency_ms_median"]
                for r in selected
                if r.metrics["decision_latency_ms_median"] is not None
            ]
            p95 = [
                r.metrics["decision_latency_ms_p95"]
                for r in selected
                if r.metrics["decision_latency_ms_p95"] is not None
            ]
            cpu = [
                r.metrics["cpu_seconds"] for r in selected if r.metrics["cpu_seconds"] is not None
            ]
            mem = [
                r.metrics["memory_mib_peak"]
                for r in selected
                if r.metrics["memory_mib_peak"] is not None
            ]
            msg = [float(r.metrics["messages"]) for r in selected]
            errors = sum(1 for r in selected if r.confusion.get("false_rejection", 0))
            rows.append(
                [
                    level,
                    LABELS[strategy],
                    len(selected),
                    _fmt(describe(lat)["median"]),
                    _fmt(describe(p95)["p95"]),
                    _fmt(describe(cpu)["median"], 4),
                    _fmt(describe(mem)["median"], 1),
                    _fmt(describe(msg)["median"], 1),
                    errors,
                ]
            )
    intro = (
        "**Logical**-device scalability. Each device has a distinct service-domain "
        "identity, a distinct 5G address and binding, a distinct WLAN logical address "
        "and binding, a distinct MQTT session and a distinct audit trail.\n\n"
        "The 25 WLAN addresses share **one** IEEE 802.11 association. This table "
        "therefore measures CA-ZTCF logical/service-domain scalability, **not** "
        "independent WiFi-radio association scalability.\n\n"
        "Levels above 25 were not validated and were not run. Nothing here may be "
        "extrapolated to 50, 100 or 1000 devices."
    )
    return _page(
        "Table J — logical-device scalability",
        intro,
        _table(
            [
                "Devices",
                "Strategy",
                "Runs",
                "Decision latency median (ms)",
                "Decision latency p95 (ms)",
                "CPU s median",
                "Peak RSS MiB median",
                "Messages median",
                "Runs with a false rejection",
            ],
            rows,
        ),
    )


# --- Table K ---------------------------------------------------------------


def table_k(runs: list[FinalRun], root: Path) -> str:
    stats_path = root / "statistics" / "primary_continuous.json"
    security_path = root / "statistics" / "primary_security.json"
    rows: list[list[Any]] = []
    if stats_path.is_file():
        for comparison in json.loads(stats_path.read_text(encoding="utf-8"))["comparisons"]:
            omnibus = comparison["omnibus"]
            if not omnibus.get("applicable"):
                rows.append(
                    [
                        comparison["dimension"],
                        comparison["scenario"],
                        comparison["metric_label"],
                        comparison["n_paired_runs"],
                        "Friedman",
                        "not applicable",
                        omnibus.get("reason", ""),
                        "-",
                        "-",
                    ]
                )
                continue
            for key, pair in sorted(comparison.get("pairwise", {}).items()):
                if not pair.get("applicable"):
                    rows.append(
                        [
                            comparison["dimension"],
                            comparison["scenario"],
                            comparison["metric_label"],
                            comparison["n_paired_runs"],
                            f"Wilcoxon {key}",
                            "not applicable",
                            pair.get("reason", ""),
                            "-",
                            "-",
                        ]
                    )
                    continue
                effect = pair.get("effect_size", {})
                ci = pair.get("paired_bootstrap_ci", {})
                rows.append(
                    [
                        comparison["dimension"],
                        comparison["scenario"],
                        comparison["metric_label"],
                        comparison["n_paired_runs"],
                        f"Wilcoxon {key}",
                        f"{pair['p_value_holm']:.5f}" if "p_value_holm" in pair else "-",
                        "yes" if pair.get("significant_holm") else "no",
                        f"{effect.get('value', '-')} ({effect.get('magnitude', '-')})",
                        f"[{ci.get('ci_lower_95', '-')}, {ci.get('ci_upper_95', '-')}]",
                    ]
                )
            if not comparison.get("pairwise"):
                rows.append(
                    [
                        comparison["dimension"],
                        comparison["scenario"],
                        comparison["metric_label"],
                        comparison["n_paired_runs"],
                        "Friedman",
                        f"{omnibus['p_value']:.5f}",
                        "yes" if omnibus["significant"] else "no (no follow-up)",
                        "-",
                        "-",
                    ]
                )
    security_rows: list[list[Any]] = []
    if security_path.is_file():
        for entry in json.loads(security_path.read_text(encoding="utf-8"))["scenarios"]:
            for name in ("paired_binary_false_acceptance", "paired_binary_false_rejection"):
                test = entry[name]
                security_rows.append(
                    [
                        entry["scenario"],
                        name.replace("paired_binary_", ""),
                        entry["n_paired_runs"],
                        "Cochran Q" if test.get("applicable") else "not applicable",
                        f"{test['p_value']:.5f}"
                        if test.get("applicable")
                        else test.get("reason", ""),
                        "yes" if test.get("significant") else "no",
                        json.dumps(test.get("successes", {})),
                    ]
                )
    intro = (
        "The frozen plan: Friedman across the three paired strategies, paired "
        "Wilcoxon signed-rank follow-up **only** where the omnibus test is "
        "significant, Holm correction across the pairwise family, matched-pairs "
        "rank-biserial effect size and a paired bootstrap 95% confidence interval on "
        "the median difference. Alpha = 0.05 on Holm-adjusted p-values.\n\n"
        "The experimental unit is the run. Mann-Whitney U is not used: the design is "
        "paired by seed."
    )
    body = _table(
        [
            "Dim",
            "Scenario",
            "Metric",
            "n",
            "Test",
            "p (Holm)",
            "Significant",
            "Effect size",
            "Bootstrap 95% CI",
        ],
        rows,
    )
    body += "\n\n## Paired binary security outcomes\n\n"
    body += (
        "One binary outcome per run — did this run produce any false acceptance, or "
        "any false rejection — across the three paired strategies.\n\n"
    )
    body += _table(
        ["Scenario", "Outcome", "n runs", "Test", "p", "Significant", "Runs affected per strategy"],
        security_rows,
    )
    return _page("Table K — statistical comparison and effect sizes", intro, body)


# --- Table L ---------------------------------------------------------------


def table_l(runs: list[FinalRun], root: Path) -> str:
    path = root / "statistics" / "ttl_sensitivity.json"
    rows: list[list[Any]] = []
    if path.is_file():
        for entry in json.loads(path.read_text(encoding="utf-8"))["scenarios"]:
            for strategy in SENSITIVITY:
                block = entry["per_lifetime"][strategy]
                counts = block["aggregate"]["counts"]
                rows.append(
                    [
                        entry["scenario"],
                        block["label"],
                        entry["token_lifetimes_s"][strategy],
                        entry["n_paired_runs"],
                        counts["TP"],
                        counts["TN"],
                        counts["FP"],
                        counts["FN"],
                        f"{_fmt(block['aggregate']['false_acceptance_rate'], 4)} "
                        f"({counts['FN']}/{block['aggregate']['false_acceptance_denominator']})",
                        block["runs_with_any_false_acceptance"],
                        _fmt(block["reauthentications"]["median"], 1),
                        _fmt(block["step_ups"]["median"], 1),
                    ]
                )
    intro = (
        "Baseline B at three token lifetimes, on the nine scenarios where a lifetime "
        "can change the outcome: each either crosses an access domain, presents "
        "evidence whose age matters, or mixes legitimate and adversarial traffic.\n\n"
        "**Sensitivity analysis, not a primary comparison.** The three lifetimes are "
        "the same algorithm, so any difference is attributable to the lifetime alone."
    )
    return _page(
        "Table L — static-continuity token lifetime sensitivity",
        intro,
        _table(
            [
                "Scenario",
                "Strategy",
                "TTL (s)",
                "Runs",
                "TP",
                "TN",
                "FP",
                "FN",
                "False acceptance (n/N)",
                "Runs with any FA",
                "Re-auth median",
                "Step-up median",
            ],
            rows,
        ),
    )


